# Build: valida paridad de claves y escribe src/lib/i18n.json
# ------------------------------------------------------------------
def main():
    es = {**_es_a(), **_es_b(), **_es_c()}
    en = {**_en_a(), **_en_b(), **_en_c()}
    only_es = set(es) - set(en)
    only_en = set(en) - set(es)
    if only_es or only_en:
        raise SystemExit(
            "i18n.py: claves desbalanceadas\n"
            + f"  solo en es: {sorted(only_es)}\n"
            + f"  solo en en: {sorted(only_en)}"
        )
    out_dir = Path(__file__).resolve().parent.parent / "src" / "lib"
    (out_dir / "i18n.json").write_text(
        json.dumps({"es": es, "en": en}, ensure_ascii=False, indent=1, sort_keys=True),
        encoding="utf-8",
    )
    print(f"i18n.py -> {out_dir / 'i18n.json'} ({len(es)} claves x 2 idiomas)")


if __name__ == "__main__":
    main()
